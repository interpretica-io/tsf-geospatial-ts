# Build helper: embed the agent-side Python scripts into a C header as
# string constants, so a test can write them onto any agent (local or
# remote) with tapi_file_create_ta(). python3 embed.py OUT.h IN.py...
import os
import sys

out = sys.argv[1]
with open(out, "w") as f:
    f.write("/* Generated by lib/py/embed.py - do not edit. */\n")
    for src in sys.argv[2:]:
        name = os.path.splitext(os.path.basename(src))[0]
        f.write("static const char tsapi_py_%s[] =\n" % name)
        with open(src) as s:
            for line in s:
                esc = (line.replace("\\", "\\\\").replace('"', '\\"')
                       .replace("\n", "\\n"))
                f.write('    "%s"\n' % esc)
        f.write("    ;\n")
